/// Draw `text` into an indexed canvas using one colour index.
pub fn draw_text(
    canvas: &mut crate::canvas::Canvas,
    text: &str,
    x: i32,
    y: i32,
    colour: u8,
) {
    let mut cx = x;
    for &byte in text.as_bytes() {
        if byte >= 32 && byte <= 126 {
            let glyph = &GLYPHS[(byte - 32) as usize];
            for (gy, row) in glyph.iter().enumerate() {
                for gx in 0..W {
                    if row & (1 << (W - 1 - gx)) != 0 {
                        canvas.set(cx + gx as i32, y + gy as i32, colour);
                    }
                }
            }
        }
        cx += W as i32;
    }
}
